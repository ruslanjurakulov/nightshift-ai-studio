def test_the_insert_policy_itself_refuses_a_browser_link_to_a_regeneration(conn, sc):
    """BR-L-030: the payment guard (a BEFORE trigger) refuses the link first,
    so the test above cannot tell whether render_jobs_insert's own clause
    (`scene_regeneration_id is null`) is there. Here the guard is switched off
    inside the rolled-back world: the policy alone must still refuse the link,
    and the same insert without the link must pass it (the clause is the reason)."""
    with world(conn, sc.bob) as (su, vid):
        with acting(conn, sc.bob.actor) as s:
            rid = press(s, vid).rows[0][0]["id"]
        su.run("alter table public.render_jobs disable trigger render_jobs_payment_guard")
        with acting(conn, sc.bob.actor) as s:
            linked = s.run("insert into public.render_jobs (channel_id, kind, params, requested_by, "
                           "scene_regeneration_id) values (%s, 'daily', '{}'::jsonb, auth.uid(), %s)",
                           [sc.bob.channel, rid])
        with acting(conn, sc.bob.actor) as s:
            plain = s.run("insert into public.render_jobs (channel_id, kind, params, requested_by) "
                          "values (%s, 'daily', '{}'::jsonb, auth.uid())", [sc.bob.channel])
        su.run("alter table public.render_jobs enable trigger render_jobs_payment_guard")
    assert not linked.ok and linked.sqlstate == "42501", linked
    assert "row-level security" in str(linked.error), linked
    assert plain.ok, plain


def test_the_service_key_cannot_pay_a_regeneration_job_with_another_hold(conn, sc):
    with world(conn, sc.bob) as (su, vid):
        with acting(conn, sc.bob.actor) as s:
            body = press(s, vid).rows[0][0]
            o = owner(s)
            # Room for a second open hold, whatever the plan's parallel limit.
            o.rows("update public.credit_reservations set status = 'released', settled_at = now() "
                   "where job_id = %s returning 1", [body["credit_ref"]])
            # Unlink its job, past the frozen-terms trigger, so the guard is
            # what is tested.
            o.conn.execute("set local session_replication_role = replica")
            o.rows("delete from public.render_jobs where scene_regeneration_id = %s returning 1", [body["id"]])
            o.rows("update public.scene_regenerations set render_job_id = null where id = %s returning 1",
                   [body["id"]])
            o.conn.execute("set local session_replication_role = origin")
            ref = o.value("select public.reserve_credits(%s, %s, 500)", [sc.bob.org, "rj-" + uuid.uuid4().hex])
            become(s, SERVICE)
            # A regeneration paid by an ordinary queue hold, not its own.
            out = s.run("insert into public.render_jobs (channel_id, kind, params, credit_ref, scene_regeneration_id) "
                        "values (%s, 'repair', %s::jsonb, %s, %s)",
                        [sc.bob.channel, json.dumps({"topic": f"regen-{sc.bob.key}", "repair_scenes": "s000"}),
                         ref["job_id"], body["id"]])
            # Another scene than the one priced, with its own hold.
            other = s.run("insert into public.render_jobs (channel_id, kind, params, credit_ref, scene_regeneration_id) "
                          "values (%s, 'repair', %s::jsonb, %s, %s)",
                          [sc.bob.channel, json.dumps({"topic": f"regen-{sc.bob.key}", "repair_scenes": "s001"}),
                           body["credit_ref"], body["id"]])
    assert not out.ok and out.sqlstate == "42501", out
    assert not other.ok and other.sqlstate == "42501", other


def test_an_ended_regeneration_is_final(conn, sc):
    with world(conn, sc.bob) as (su, vid):
        with acting(conn, sc.bob.actor) as s:
            body = press(s, vid).rows[0][0]
            become(s, SERVICE)
            s.value("select public.finish_scene_regeneration(%s, %s, false, 'failed', 'x', null)",
                    [body["id"], body["render_job_id"]])
            o = owner(s)
            out = o.run("update public.scene_regenerations set status = 'queued', finished_at = null "
                        "where id = %s", [body["id"]])
            gone = o.run("delete from public.scene_regenerations where id = %s", [body["id"]])
    assert not out.ok and out.sqlstate == "42501", out
    assert not gone.ok and gone.sqlstate == "42501", gone
