def test_a_failed_regeneration_releases_the_hold_and_keeps_the_old_scene(conn, sc):
    with world(conn, sc.bob, review_state="approved") as (su, vid):
        before = available(su, sc.bob.org)
        old_manifest = su.value("select manifest from public.videos where video_id = %s", [vid])
        with acting(conn, sc.bob.actor) as s:
            body = press(s, vid).rows[0][0]
            become(s, SERVICE)
            started = s.value("select public.start_scene_regeneration(%s, %s)", [body["id"], body["render_job_id"]])
            ended = s.value("select public.finish_scene_regeneration(%s, %s, false, 'provider_unavailable', "
                            "'the generator is not configured on this worker', null)",
                            [body["id"], body["render_job_id"]])
            again = s.value("select public.finish_scene_regeneration(%s, %s, true, null, null, null)",
                            [body["id"], body["render_job_id"]])
            o = owner(s)
            h, r = holds(o, sc.bob.org), regens(o, vid)
            after = available(o, sc.bob.org)
            v = o.rows("select manifest, review_state from public.videos where video_id = %s", [vid])[0]
    assert started["provider"] == "kling" and started["model"] == "kling-v2-6", started
    assert ended["status"] == "failed" and again["replayed"] is True and again["status"] == "failed"
    assert h[0][2] == "released" and h[0][3] is None, h
    assert float(after) == float(before), "a failed regeneration kept credits"
    assert r[0][1] == "failed" and float(r[0][8]) == 0
    # The old scene stays: the Video IR is untouched and so is the approval
    # of a cut that did not change.
    assert v[0] == old_manifest and v[1] == "approved", v


