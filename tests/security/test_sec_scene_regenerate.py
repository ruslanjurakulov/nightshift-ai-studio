def test_the_press_holds_exactly_the_quote_and_queues_one_repair_of_that_scene(conn, sc):
    with world(conn, sc.bob) as (su, vid):
        before = available(su, sc.bob.org)
        with acting(conn, sc.bob.actor) as s:
            q = quote(s, vid)
            p = press(s, vid, prompt="the harbour at dawn, wider")
            o = owner(s)
            h, r, j = holds(o, sc.bob.org), regens(o, vid), jobs(o, vid)
            after = available(o, sc.bob.org)
    assert q.ok and float(q.rows[0][0]["credits"]) == GEN, q
    # BR-L-031: what a member reads over PostgREST is display-safe — no
    # generator, model or price-unit name, only the kind of source.
    body = q.rows[0][0]
    assert body["source_kind"] == "generated", body
    assert not {"provider", "model", "missing_unit", "unit", "clip_unit"} & set(body), body
    assert "kling" not in json.dumps(body), body
    assert p.ok, p
    assert len(h) == 1 and float(h[0][1]) == GEN and h[0][2] == "open", h
    assert float(before) - float(after) == GEN
    assert len(r) == 1
    _, status, kind, provider, model, explicit, quoted, ref, charged, job_id = r[0]
    # The same generator the scene was made with, never another one.
    assert (status, kind, provider, model, explicit) == ("queued", "generated", "kling", "kling-v2-6", False)
    assert float(quoted) == GEN and ref == h[0][0] and charged is None
    assert len(j) == 1 and j[0][0] == job_id and j[0][1] == "repair" and j[0][3] == ref
    assert j[0][2] == {"topic": f"regen-{sc.bob.key}", "repair_scenes": "s000"}, j[0][2]


