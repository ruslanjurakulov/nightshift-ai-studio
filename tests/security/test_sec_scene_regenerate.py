"""Migration 0076: regenerating one scene is priced, confirmed, paid once, made
with the same source, and decided only by someone who may start runs.

What would break without these:

* another organization quotes, or regenerates (and pays with the victim's
  credits for) a scene of a tenant's video; a missing video and another
  organization's read differently (an oracle);
* a member who may only read the channel starts a paid regeneration;
* a replayed idempotency key holds twice or queues two jobs, or a reused key
  quietly runs a different request;
* the price changes between the quote and the press and the new price is
  held anyway; a press without a price spends;
* an unset price reads as 0 and runs for free;
* a failed regeneration keeps the credits, or replaces the old scene, or voids
  the approval of a cut that did not change;
* two presses at once hold twice or queue two jobs on one run;
* a scene made by a generator is regenerated by another one, or silently from
  stock; a published video is changed;
* a browser links a job to a regeneration, or a job is linked to another
  regeneration's hold, or a regeneration's job is held to the whole-video floor.

Isolation of scene_regenerations (read / update / delete / insert, row by row)
is covered by test_sec_isolation.py through sec_expectations.TABLES.
"""

from __future__ import annotations

import json
import threading
import uuid
from contextlib import contextmanager

import psycopg
from psycopg import sql

import sec_db
from sec_db import ANON, SERVICE, acting, as_superuser
from sec_scene_regen_0076 import held_id, manifest_json

# A generated scene (1 clip): 3 + 7 = 10. A stock scene: 3, floored to 5.
# video_minute is deliberately high: a regeneration is never held to the
# whole-video length floor.
PRICES = {"scene_regenerate": 3, "scene_regenerate_clip_kling": 7, "job_minimum": 5, "video_minute": 400}
GEN, STOCK = 10, 5


def owner(s):
    """The same transaction, read as the database owner: the ground truth an
    attack is checked against, before the rollback takes it away."""
    s.conn.execute("reset role")
    return s


def become(s, who):
    """The same transaction, continued as another API caller (the worker's
    service key after the person's press), so the whole story rolls back
    together."""
    s.conn.execute("reset role")
    s.conn.execute("select set_config('request.jwt.claims', %s, true)", [json.dumps(who.claims())])
    s.conn.execute("select set_config('request.jwt.claim.role', %s, true)", [who.role])
    s.conn.execute(sql.SQL("set local role {}").format(sql.Identifier(who.role)))
    return s


def _set_prices(su, prices):
    for unit, rate in prices.items():
        su.rows("insert into public.credit_prices (unit, credits_per_unit, margin) values (%s, %s, 0) "
                "on conflict (unit) do update set credits_per_unit = excluded.credits_per_unit, margin = 0 "
                "returning 1", [unit, rate])


def _held_video(su, t, slug, *, review_state="pending", **mkw):
    vid = held_id(t.channel, slug)
    su.rows("insert into public.videos (video_id, channel_id, title, slug, review_state, publish_state, manifest) "
            "values (%s, %s, 'Held', %s, %s, 'held', %s::jsonb) returning 1",
            [vid, t.channel, slug, review_state, manifest_json(**mkw)])
    return vid


@contextmanager
def world(conn, t, *, prices=PRICES, slug=None, **mkw):
    """A rolled-back world with the price list and one held (not uploaded)
    run of tenant ``t``. Everything made inside disappears with it."""
    with as_superuser(conn, commit=False) as su:
        if prices:
            _set_prices(su, prices)
        vid = _held_video(su, t, slug or f"regen-{t.key}", **mkw)
        yield su, vid


def quote(s, vid, scene="s000", source="same"):
    return s.run("select public.quote_scene_regenerate(%s, %s, %s)", [vid, scene, source])


def press(s, vid, scene="s000", *, prompt=None, source="same", max_credits=GEN, key=None):
    return s.run("select public.request_scene_regenerate(%s, %s, %s, %s, %s::numeric, %s)",
                 [vid, scene, prompt, source, max_credits, key or f"press-{uuid.uuid4().hex}"])


def holds(su, org, *, fresh=True) -> list:
    """The organization's regeneration holds — by default only those placed in
    this (rolled-back) transaction: now() is its start time."""
    return su.rows("select job_id, amount, status, captured from public.credit_reservations "
                   "where org_id = %s and job_id like 'rj-sr-%%' "
                   + ("and created_at >= now() " if fresh else "") + "order by created_at", [org])


def regens(su, vid) -> list:
    return su.rows("select id, status, source_kind, provider, model, explicit_stock, quoted_credits, credit_ref, "
                   "charged_credits, render_job_id from public.scene_regenerations where video_id = %s "
                   "order by created_at", [vid])


def jobs(su, vid) -> list:
    return su.rows("select j.id, j.kind, j.params, j.credit_ref, j.scene_regeneration_id from public.render_jobs j "
                   "join public.scene_regenerations r on r.id = j.scene_regeneration_id where r.video_id = %s",
                   [vid])


def available(su, org):
    return su.value("select balance - reserved from public.credit_accounts where org_id = %s", [org])


def _accept_invite(s):
    s.rows("select public.accept_org_invite(id) from public.my_invites() limit 1")


