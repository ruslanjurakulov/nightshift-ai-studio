--
-- WHAT COMES BACK: 0075's create_creative_job, which does not ask for an acknowledgement. A model that requires one
-- (model_registry.requires_acknowledgement, spec.requires_acknowledgement) then starts without it: apply this only while no
-- such model is on sale (today: runway-gen4.5 and runway-gen4-turbo require likeness_photo and are not sold).
-- WHAT IS KEPT: the record. rights_acknowledgements, its append-only triggers, rights_acknowledgement_kinds and the
--   model_registry.requires_acknowledgement column stay as they are (who took responsibility for what must outlive a rollback);
--   applying 0174 again picks them up as its own.
-- WHAT IS LOST: the two calls the app makes (acknowledge_rights, rights_acknowledgement_status) and the two helpers. The Studio
--   then answers its acknowledgement dialog with "not available" and starts nothing through it.
--
-- WHAT IT DOES, in one transaction:
--   0. REFUSES (changes nothing) if create_creative_job is not 0174's body (a later change would be undone).
--   1. Puts 0075's create_creative_job back, verbatim, with 0075's grant (authenticated only).
--   2. Drops acknowledge_rights, rights_acknowledgement_status, rights_acknowledgement_missing, rights_acknowledgement_required.
--   3. Asserts the end state.

