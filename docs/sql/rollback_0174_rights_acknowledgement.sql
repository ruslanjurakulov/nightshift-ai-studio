       where oid = to_regprocedure('public.create_creative_job(uuid, text, text, jsonb, text, text, numeric)'))
       is distinct from '4c74918fd9d938c8fe4f5a3d26a09d84'
     or not has_function_privilege('authenticated', 'public.create_creative_job(uuid, text, text, jsonb, text, text, numeric)', 'EXECUTE')
     or has_function_privilege('anon', 'public.create_creative_job(uuid, text, text, jsonb, text, text, numeric)', 'EXECUTE')
     or has_function_privilege('service_role', 'public.create_creative_job(uuid, text, text, jsonb, text, text, numeric)', 'EXECUTE') then
    raise exception 'rollback 0174 end state: create_creative_job is not 0075''s authenticated-only body';
  end if;
