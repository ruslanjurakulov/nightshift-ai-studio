     or to_regprocedure('public.rights_acknowledgement_status(uuid, text, text[])') is not null then
    raise exception 'rollback 0174 end state: an acknowledgement call is still there';
  end if;
  if to_regclass('public.rights_acknowledgements') is null then
    raise exception 'rollback 0174 end state: the record (rights_acknowledgements) is gone';
  end if;
end $$;

