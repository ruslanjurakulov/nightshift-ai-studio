  check (language in ('en', 'ru', 'uz')
         and aspect in ('16:9', '9:16', '1:1')
         and target_seconds between 60 and 1200
         and (resolution is null or resolution in ('480p', '720p', '768p', '1080p', '2k', '4k')));

