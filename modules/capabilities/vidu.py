"""Vidu Q3 and Q4 preview (Shengshu's own API): text-to-video, image-to-video and start/end-frame video.

Sources, all on platform.vidu.com/docs (each page as markdown, append ``.md``) and read 2026-10-25:
``api-reference/video-models/vidu-q3/{text-to-video,image-to-video,start-end-to-video,reference-to-video}``,
``.../vidu-q4-preview/{image-to-video,reference-to-video}``, ``api-reference/task-management/{task-detail,
cancel-task,account-balance}``, ``api-reference/other-documentation/error-codes``, ``overview/{pricing,
model-map,faq}``, ``terms-and-policies/{usage-and-limits,content-moderation,terms-of-use}``.

* A task is created with ``POST /ent/v2/text2video`` | ``img2video`` | ``start-end2video`` and answers
  ``{"task_id", "state", "credits", ...}``; ``GET /ent/v2/tasks/{id}/creations`` answers ``state``
  (created | queueing | processing | success | failed), ``err_code`` and, on success,
  ``creations[]`` with ``url``, ``cover_url`` and ``watermarked_url``. ONE poll path serves every
  endpoint, so the task id alone is enough.
* Authentication is ``Authorization: Token <key>`` (not ``Bearer``).
* EVERY LINK IS VALID FOR 24 HOURS ("Creation URL, valid for 24 hours"). ``fetch`` runs straight after
  the poll that reports ``success``; a clip not stored within a day is gone. The worker must not park a
  finished task.
* Vidu runs at most 5 concurrent tasks per ORGANISATION (not per key); the rest queue. That is Vidu's
  organisation, i.e. every Nightshift customer shares it.

What is sent, and why: the price is credits per second of output by model and resolution, so
``duration`` and ``resolution`` are required and sent as given (the vendor's own defaults, 5 s and 720p,
are priced differently from what a person was quoted). ``off_peak`` is never sent (half price, but the
task may take 48 h and is cancelled and refunded if it does not finish; not a thing to sell by default).
``audio`` is sent only when the job names it. Image-to-video ALWAYS sends ``is_rec: false``: on
Q4 preview the vendor's default is ``true`` (the system writes a prompt, ignores the one given, and the
pricing page bills 10 credits per 5 recommended prompts). Not sent: ``seed``, ``payload``, ``callback_url``,
``voice_id`` and the watermark / metadata options.

Not wired, so nobody can reach them: reference-to-video (``viduq3``, ``viduq3-mix``, ``viduq3-turbo`` with
subjects, ``viduq4-preview``): the registry has no reference-to-video capability; the other Q3 models
(``viduq3-ad``, ``viduq3-drama``), Q2 and older, the audio, image, lip-sync, effect and solution products.
Q4 preview has no text-to-video or start/end endpoint in the docs read.

RESULT LINKS: the docs print placeholders for ``creations[].url`` and name no real host (the only Vidu
hosts on any page read are ``image01.cf.vidu.studio`` and ``scene-aliyun.vidu.zone``, both for sample
media). ``RESULT_HOSTS`` is therefore EMPTY: a link is refused (fail closed), the refusal names the host it
saw and carries the ``SPEND MAY HAVE OCCURRED`` note, and the first real probe fails with that host in its
message. A person reads it, checks it is Vidu's, and puts it in ``RESULT_HOSTS`` on purpose. The 24 hour link
outlives that: fetch again after the host is pinned.

WATERMARK: Vidu returns ``url`` and ``watermarked_url``. ``STORE_WATERMARKED`` (False) stores ``url``. The
Terms of Use (clause 4, "Content Generated by End Users") say neither Nightshift nor its end users "must not
remove, falsify, cover the sign that can distinguish those output generated by using deep synthesis
technology"; the file keeps Vidu's default metadata label (no ``meta_data`` is sent), and whether the missing
visible mark is enough is an owner decision that has not been taken. Flip the constant to store the marked file.

BILLING: the pricing page says "Videos that fail to generate do not consume credits (including failures
caused by content moderation rejection)". That is Vidu's claim, not verified here; nothing in this module tells a
person a failed task was free.

TERMS: ``terms_gate: terms_review_required``. The Terms of Use (effective 2025-01-23) let the customer
"integrate the API into your applications and authorize your end users" (clause 4, first paragraph), but
the same clause ends "You may not sell the Vidu-related technology directly or indirectly without obtaining
the necessary approval from regulatory authorities and the prior consent of us." Whether a credits product
sells "the technology" is for Vidu to confirm in writing; the entries stay unsellable until it does.
"""

from __future__ import annotations

import re
from typing import Dict, List, Optional

from modules.capabilities.base import (
    E_AUTH,
    E_BAD_REQUEST,
    E_BAD_RESPONSE,
    E_NOT_FOUND,
    E_POLICY,
    E_QUOTA,
    E_RATE_LIMITED,
    E_UNAVAILABLE,
    FAILED,
    I2V,
    PENDING,
    SUCCEEDED,
    T2V,
    AdapterError,
    CapabilityRequest,
    HttpAdapter,
    Output,
    PollResult,
    ProviderTask,
    json_body,
)
from modules.capabilities.pictures import inline_picture
from modules.capabilities.safe_fetch import UNCONFIRMED, SafeResultMixin, after_completion, unconfirmed

#: See RESULT LINKS above: nothing is known, so nothing is allowed.
RESULT_HOSTS: tuple = ()

#: A task id: letters, digits, "-" and "_" only (no "." so ".." cannot walk the path up, no "/" or ":").
_ID = re.compile(r"^[A-Za-z0-9_-]{1,100}$")
#: Said after any task Vidu reports as failed. Its pricing page says failed (and moderated) tasks consume no
#: credits; that is its claim, not something this adapter has seen.
SPEND_UNKNOWN = ("SPEND UNKNOWN: Vidu's pricing page claims failed and moderated tasks consume no credits (a vendor "
                 "claim, unverified here); check the Vidu usage page before assuming nothing was spent")
#: ``err_code`` / ``reason`` -> our code (platform.vidu.com/docs/api-reference/other-documentation/error-codes).
_ERRORS = {
    "Unauthorized": E_AUTH, "Forbidden": E_AUTH,
    "CreditInsufficient": E_QUOTA,
    "TooManyRequests": E_RATE_LIMITED, "QuotaExceeded": E_RATE_LIMITED, "SystemThrottling": E_RATE_LIMITED,
    "TaskNotFound": E_NOT_FOUND, "CreationNotFound": E_NOT_FOUND, "NotFound": E_NOT_FOUND,
    "TaskPromptPolicyViolation": E_POLICY, "AuditSubmitIllegal": E_POLICY, "CreationPolicyViolation": E_POLICY,
    "PhotoAuditNotPass": E_POLICY, "AuditFailed": E_POLICY, "FaceDetectNotPass": E_POLICY,
    "BadRequest": E_BAD_REQUEST, "FieldLacking": E_BAD_REQUEST, "FieldUnwanted": E_BAD_REQUEST,
    "FieldInvalid": E_BAD_REQUEST, "FieldItemCountOutOfRange": E_BAD_REQUEST, "PageSizeOutOfRange": E_BAD_REQUEST,
    "ImageDownloadFailure": E_BAD_REQUEST, "ImageFormatInvalid": E_BAD_REQUEST, "ImageSizeInvalid": E_BAD_REQUEST,
    "ImageCheckBodyJointsFailed": E_BAD_REQUEST, "ImageCheckFaceFailed": E_BAD_REQUEST,
    "ImageObjectsUndetected": E_BAD_REQUEST, "NoFaceDetected": E_BAD_REQUEST, "MultiFaceDetected": E_BAD_REQUEST,
    "FaceDetectFailure": E_BAD_REQUEST,
    "ModelUnavailable": E_UNAVAILABLE, "InternalServiceFailure": E_UNAVAILABLE, "OperationInProcess": E_UNAVAILABLE,
    "UserCancelled": E_UNAVAILABLE, "Canceled": E_UNAVAILABLE, "Unknown": E_UNAVAILABLE,
}
_BASE_RATIOS = ("16:9", "9:16", "3:4", "4:3", "1:1")
_ENDPOINTS = {"t2v": "text2video", "i2v": "img2video", "end": "start-end2video"}
#: Vidu's own spelling of a resolution: lower case "540p" / "720p" / "1080p", but "2K" / "4K".
_WIRE_RESOLUTION = {"2k": "2K", "4k": "4K"}


class ViduVideoAdapter(SafeResultMixin, HttpAdapter):
    """Vidu Q3 Pro / Turbo / Pro Fast and Q4 preview: 1-16 s, with generated audio."""

    key = "video.vidu"
    key_env = ("VIDU_API_KEY",)
    base_url_env = "VIDU_BASE_URL"
    default_base_url = "https://api.vidu.com"
    capabilities = (T2V, I2V)
    audio_capabilities = (T2V, I2V)          # ``audio`` (default true on the vendor's side)
    resolution_capabilities = (T2V, I2V)     # always sent
    end_frame_capabilities = (I2V,)          # start-end2video
    result_hosts = RESULT_HOSTS
    #: The key rides every call in an ``Authorization`` header: a 3xx is an error, never followed.
    follow_redirects = False
    timeout = 60
    #: See WATERMARK above: an owner decision, recorded here so it is one line to change.
    STORE_WATERMARKED = False
    #: A picture goes inline as base64 (a third larger). The docs cap the decoded picture below 10 MB and, on
    #: the pages that state a body limit, the HTTP body at 20 MB: two pictures of 7 MB stay under both.
    MAX_IMAGE_BYTES = 7 * 1024 * 1024
    #: vendor model -> what it serves. ``modes`` are the endpoints it has. The longest prompt is the registry's
    #: ``max_prompt_chars`` (ours, 2000: the docs say 20000 on most Q3 pages and 5000 on Turbo text-to-video, an
    #: update notice of 2025-09-17 says 2000, so the smallest is the cap until a probe says more).
    SPECS = {
        "viduq3-pro": {"modes": ("t2v", "i2v", "end"), "resolutions": ("540p", "720p", "1080p"),
                       "durations": tuple(range(1, 17)), "ratios": _BASE_RATIOS},
        "viduq3-turbo": {"modes": ("t2v", "i2v", "end"), "resolutions": ("540p", "720p", "1080p"),
                         "durations": tuple(range(1, 17)), "ratios": _BASE_RATIOS},
        "viduq3-pro-fast": {"modes": ("i2v",), "resolutions": ("720p", "1080p"),
                            "durations": tuple(range(1, 17)), "ratios": ()},
        "viduq4-preview": {"modes": ("i2v",), "resolutions": ("540p", "720p", "1080p", "2k", "4k"),
                           "durations": tuple(range(3, 17)), "ratios": ()},
    }

    def auth_headers(self) -> Dict[str, str]:
        return {"Authorization": f"Token {self.api_key()}"}

    def vendor_error_code(self, status: int, text: str) -> Optional[str]:
        # Never for a 5xx: a gateway can answer 502 / 503 / 504 in front of a Vidu that already took the task, and a
        # vendor word ("SystemThrottling") must not turn that into a refusal. The status decides, so it stays unconfirmed.
        if status >= 500:
            return None
        return _ERRORS.get(str(json_body(text).get("reason") or ""))

    def _error_body(self, data, *, at_submit: bool = False) -> Optional[AdapterError]:
        """A 200 whose body is Vidu's error shape (``code`` + ``reason`` + ``message``, the shape the cancel page
        shows with a 200 status) and holds no task: the vendor's refusal, not a lost answer. At submit, a refusal that
        reads as an outage (``InternalServiceFailure``, ``ModelUnavailable``, a word we do not know) proves nothing about
        whether a task was started, so it says so like any other lost answer."""
        if isinstance(data, dict) and data.get("reason") and "task_id" not in data and "state" not in data:
            reason = str(data.get("reason"))
            code = _ERRORS.get(reason, E_UNAVAILABLE)
            text = self.message(f"{reason}: {data.get('message') or ''}".strip(": "))
            if at_submit and code == E_UNAVAILABLE:
                text = f"{UNCONFIRMED}. {text}"
            return AdapterError(code, text)
        return None

    @staticmethod
    def _mode(request: CapabilityRequest) -> str:
        if request.capability == T2V:
            return "t2v"
        return "end" if request.end_image else "i2v"

    def _spec_problems(self, request: CapabilityRequest, vendor_model: str) -> List[str]:
        spec = self.SPECS.get(vendor_model)
        if spec is None:
            return [f"{vendor_model!r} is not a Vidu model this adapter knows"]
        out: List[str] = []
        mode = self._mode(request)
        if mode not in spec["modes"]:
            what = {"t2v": "text-to-video", "i2v": "image-to-video", "end": "a start and end frame"}[mode]
            out.append(f"{vendor_model} has no {what} here")
        if request.resolution not in spec["resolutions"]:
            out.append(f"resolution {request.resolution or '(none)'} is not offered by {vendor_model}: the price "
                       f"depends on it, so it is never defaulted")
        if request.duration_s not in spec["durations"]:
            out.append(f"duration {request.duration_s if request.duration_s is not None else '(none)'} s is not "
                       f"offered by {vendor_model} ({spec['durations'][0]} to {spec['durations'][-1]}): the price "
                       f"is per second, so it is never defaulted")
        if request.negative_prompt:
            out.append("Vidu takes no negative prompt")
        if request.capability == T2V:
            if not request.prompt.strip():
                out.append("prompt is empty")
            if request.aspect_ratio is not None and request.aspect_ratio not in spec["ratios"]:
                out.append(f"aspect ratio {request.aspect_ratio} is not offered by {vendor_model}")
            if request.input_images:
                out.append("a picture does not apply to text-to-video")
        else:
            if not request.input_images:
                out.append("i2v needs a first-frame picture")
            elif len(request.input_images) > 1:
                out.append("Vidu takes one first-frame picture")
            if request.aspect_ratio:
                out.append("a clip made from pictures keeps their shape: an aspect ratio does not apply here")
        return out

    def problems(self, request: CapabilityRequest, entry) -> List[str]:
        out = super().problems(request, entry)
        out.extend(self._spec_problems(request, entry.vendor_model_for(request.capability)))
        return out

    def _picture(self, ref: str) -> str:
        return inline_picture(ref, max_bytes=self.MAX_IMAGE_BYTES, who="Vidu")

    def submit(self, request: CapabilityRequest, vendor_model: str) -> ProviderTask:
        self.require_key()
        bad = self._spec_problems(request, vendor_model)
        if bad:
            # Nothing has been sent: this is a refusal, not a lost answer.
            raise AdapterError(E_BAD_REQUEST, "; ".join(bad), not_accepted=True)
        mode = self._mode(request)
        body: dict = {"model": vendor_model, "duration": int(request.duration_s),
                      "resolution": _WIRE_RESOLUTION.get(request.resolution, request.resolution)}
        prompt = request.prompt.strip()
        if prompt:
            body["prompt"] = prompt
        if mode == "t2v":
            body["aspect_ratio"] = request.aspect_ratio or "16:9"
        else:
            # Every picture is read and checked BEFORE anything is sent.
            images = [self._picture(str(request.input_images[0]))]
            if mode == "end":
                images.append(self._picture(str(request.end_image)))
            body["images"] = images
            if mode == "i2v":
                # Q4 preview's default is true: the system would write (and bill) a prompt and ignore ours.
                body["is_rec"] = False
        if request.audio is not None:
            body["audio"] = bool(request.audio)
        data = self.submit_json(f"{self.base_url}/ent/v2/{_ENDPOINTS[mode]}", body)
        err = self._error_body(data, at_submit=True)
        if err:
            raise err
        tid = data.get("task_id") if isinstance(data, dict) else None
        if isinstance(tid, int) and not isinstance(tid, bool) and tid >= 0:
            tid = str(tid)                       # the docs say a string; a plain integer is the same id
        if not isinstance(tid, str) or not _ID.fullmatch(tid):
            # The vendor answered 2xx: a task probably exists, and it bills.
            raise unconfirmed("the answer carries no usable task_id")
        return ProviderTask(self.key, vendor_model, tid)

    def poll(self, task: ProviderTask) -> PollResult:
        self.require_key()
        tid = str(task.task_id or "")
        if not _ID.fullmatch(tid):
            raise AdapterError(E_NOT_FOUND, "task id has an unexpected shape")
        data = self.get(f"{self.base_url}/ent/v2/tasks/{tid}/creations")
        err = self._error_body(data)
        if err:
            raise err
        data = data if isinstance(data, dict) else {}
        state = str(data.get("state") or "").lower()
        if state == "success":
            key = "watermarked_url" if self.STORE_WATERMARKED else "url"
            creations = data.get("creations")
            url = next((c[key] for c in (creations if isinstance(creations, list) else [])
                        if isinstance(c, dict) and isinstance(c.get(key), str) and c[key]), None)
            if url is None:
                # The vendor says the clip exists (and bills it): we just were not given the link.
                raise after_completion(AdapterError(E_BAD_RESPONSE, f"success without creations[].{key}"))
            return self.checked_outputs(PollResult(SUCCEEDED, [Output("video/mp4", url=url)]))
        if state == "failed":
            code = str(data.get("err_code") or "")
            text = self.message(code or "the task failed")
            return PollResult(FAILED, error=AdapterError(_ERRORS.get(code, E_UNAVAILABLE), f"{text}. {SPEND_UNKNOWN}"))
        return PollResult(PENDING)


ADAPTERS = (ViduVideoAdapter,)
