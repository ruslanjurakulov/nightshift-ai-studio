#!/usr/bin/env python3
"""Write the web's twin of which capabilities take reference pictures, per model.

    python tools/ref_capabilities_twin.py          # rewrite command-center/lib/brain/ref-capabilities.json
    python tools/ref_capabilities_twin.py --check  # exit 1 when the file is stale

The fact lives in the worker's adapters (``reference_capabilities`` on each class in
``modules/capabilities``): ``creative_adapters`` refuses a job whose references reach a
capability its adapter does not list, as a bad_request after the credits were held.
The Command Center's character-sheet gate (command-center/lib/brain/ref-sheets.ts)
must read the same fact, and the web image is built from ``command-center/`` alone,
so the fact is copied there by this script and ``tests/test_ref_capabilities_twin.py``
fails when the copy drifts. Once the registry carries ``ref_capabilities`` itself
(S2), the gate reads the registry first and this twin only where the field is absent.

Every registry model is listed, an empty list included: a model missing from the file
is unknown to the gate (closed), never "takes none" by omission.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
OUT = ROOT / "command-center" / "lib" / "brain" / "ref-capabilities.json"


def build() -> dict:
    from modules.capabilities import ADAPTERS

    models = json.loads((ROOT / "schemas" / "model_registry.json").read_text(encoding="utf-8"))["models"]
    out = {}
    for m in sorted(models, key=lambda x: x["id"]):
        adapter = ADAPTERS.get(m.get("adapter"))
        if adapter is None:
            continue  # no adapter on this deployment: unknown, so not listed
        caps = [c for c in getattr(adapter, "reference_capabilities", ()) if c in m["capabilities"]]
        out[m["id"]] = sorted(caps)
    return {"_note": "generated by tools/ref_capabilities_twin.py from modules/capabilities; do not edit", "models": out}


def render(data: dict) -> str:
    return json.dumps(data, indent=2, sort_keys=True) + "\n"


def main(argv: list) -> int:
    text = render(build())
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("command-center/lib/brain/ref-capabilities.json is stale: run python tools/ref_capabilities_twin.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
